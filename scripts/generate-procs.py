#!/usr/bin/env python3
"""Generates src/procs.rs: the table of wgpuGetProcAddress, every C function this library
implements (src/lib.rs, and the Metal interop of src/interop.rs on Apple platforms). Run it after
adding or removing one; the unimplemented functions (src/unimplemented.rs) are not in it, so a
lookup of one returns null."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
pattern = re.compile(r'#\[no_mangle\]\s*pub (?:unsafe )?extern "C" fn (wgpu[A-Za-z0-9]+)')
common = sorted(set(pattern.findall((root / "src/lib.rs").read_text())))
apple = sorted(set(pattern.findall((root / "src/interop.rs").read_text())))

lines = [
    "//! The procedures of `wgpuGetProcAddress`: every C function this library implements, by name.",
    "//! Generated by `scripts/generate-procs.py`; do not edit.",
    "",
    "use crate::native;",
    "",
    "/// The address of `name` as a `WGPUProc`.",
    "macro_rules! proc_of {",
    "    ($function:path) => {",
    "        // SAFETY: a C function pointer, called through the type its name declares.",
    "        Some(unsafe { std::mem::transmute::<*const (), unsafe extern \"C\" fn()>($function as *const ()) })",
    "    };",
    "}",
    "",
    "/// The procedure `name` of this library, or `None` when it implements none of that name.",
    "pub fn lookup(name: &[u8]) -> native::WGPUProc {",
    "    match name {",
]
for function in common:
    lines.append(f'        b"{function}" => proc_of!(crate::{function}),')
lines.append('        b"wgpuGetProcAddress" => proc_of!(wgpuGetProcAddress),')
for function in apple:
    lines.append('        #[cfg(any(target_os = "macos", target_os = "ios"))]')
    lines.append(f'        b"{function}" => proc_of!(crate::interop::{function}),')
lines += [
    "        _ => None,",
    "    }",
    "}",
    "",
    "#[no_mangle]",
    "pub unsafe extern \"C\" fn wgpuGetProcAddress(proc_name: native::WGPUStringView) -> native::WGPUProc {",
    "    if proc_name.data.is_null() {",
    "        return None;",
    "    }",
    "    let length = if proc_name.length == crate::conv::WGPU_STRLEN {",
    "        // SAFETY: a NUL-terminated name (`WGPU_STRLEN`).",
    "        unsafe { std::ffi::CStr::from_ptr(proc_name.data) }.to_bytes().len()",
    "    } else {",
    "        proc_name.length",
    "    };",
    "    // SAFETY: the name's bytes, borrowed for the lookup.",
    "    lookup(unsafe { std::slice::from_raw_parts(proc_name.data.cast::<u8>(), length) })",
    "}",
    "",
]
(root / "src/procs.rs").write_text("\n".join(lines))
print(len(common), "procedures,", len(apple), "on Apple platforms")
